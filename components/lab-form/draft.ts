import {
  CHEM_PROCESSES,
  CONTACT_CHANNELS,
  FILM_FORMATS,
  labPath,
  type ContactChannel,
  type FilmFormat,
  type HistoryChange,
  type LabStatus,
} from "@/lib/labs/paths";
import type { LabDetail } from "@/lib/queries/labs";

/**
 * The form's own model of a lab, and the diff it produces.
 *
 * This is the half of B4 that has to be right. The form submits leaf changes,
 * not a document (lib/labs/paths.ts), so this file is where a contributor's
 * typing becomes the set of leaves they actually touched — and anything it emits
 * that they did not change silently reverts somebody else's work.
 *
 * Every field is held as a string, the way a form holds it. Parsing happens at
 * diff time, once, so `"180"` and `" ฿180 "` produce the same leaf and neither
 * produces a change when the stored value is already 180. A model that stored
 * numbers would have to decide what an empty input means on every keystroke;
 * this one decides it once, here.
 *
 * Pure and free of React on purpose: the diff is the thing worth testing, and a
 * test should not have to render anything to reach it.
 */

export type DraftDay =
  { closed: true } | { closed: false; open: string; close: string };

export type DraftContact = {
  /** Generated by the form, so add, edit and remove are one shape. */
  id: string;
  channel: ContactChannel;
  value: string;
};

export type DraftCustom = { id: string; label: string; note?: string };

export type DraftStock = {
  filmStockId: string;
  name: string;
  formats: FilmFormat[];
};

/** One cell of the pricing matrix, as typed rather than as stored. */
export type DraftCell = {
  /** "180", "฿180", "" — parsed at diff time. */
  price: string;
  /** "2" or "2-4" days. One input, because that is what the prototype draws. */
  turnaround: string;
};

export type LabDraft = {
  nameEn: string;
  nameTh: string;
  areaEn: string;
  areaTh: string;
  street: string;
  landmarkNote: string;
  status: LabStatus;
  statusNote: string;
  location: { lat: number; lng: number } | null;
  /** Seven days, or null when nobody has entered a schedule at all. */
  hours: DraftDay[] | null;
  processes: Record<string, boolean>;
  scanners: Record<string, boolean>;
  /** Keyed `${process}.${format}`. */
  pricing: Record<string, DraftCell>;
  /** Curated services, keyed by catalog key. */
  services: Record<string, { on: boolean; note: string }>;
  customServices: DraftCustom[];
  /** Curated supplies, keyed by catalog key. */
  supplies: Record<string, boolean>;
  customSupplies: DraftCustom[];
  contacts: DraftContact[];
  stock: DraftStock[];
};

export const CELL_KEYS = CHEM_PROCESSES.flatMap((process) =>
  FILM_FORMATS.map((format) => ({
    process,
    format,
    key: `${process}.${format}`,
  })),
);

// ---------------------------------------------------------------------------
// Parsing what a person types
// ---------------------------------------------------------------------------

/** `" ฿1,180 "` → 1180. Anything that is not a number is "not entered". */
export function parsePrice(input: string): number | null {
  const cleaned = input.replace(/[฿,\s]/g, "");
  if (cleaned === "") return null;
  const value = Number(cleaned);
  return Number.isFinite(value) && value >= 0 ? value : null;
}

export function formatPrice(value: number | null): string {
  return value === null ? "" : String(value);
}

/**
 * `"2"` → 2 days. `"2-4"` → 2 to 4.
 *
 * One input rather than two number boxes, because the prototype draws one and
 * because "2-4" is how a person says it. An en dash counts: it is what a phone
 * keyboard and a paste from a website both produce.
 */
export function parseTurnaround(input: string): {
  min: number | null;
  max: number | null;
} {
  const cleaned = input.replace(/\s|days?/gi, "");
  if (cleaned === "") return { min: null, max: null };

  const [first, second] = cleaned.split(/[-–—]/);
  const min = toDay(first);
  const max = second === undefined ? null : toDay(second);
  return min === null ? { min: null, max: null } : { min, max };
}

function toDay(part: string | undefined): number | null {
  if (!part) return null;
  const value = Number(part);
  return Number.isInteger(value) && value > 0 ? value : null;
}

export function formatTurnaround(
  min: number | null,
  max: number | null,
): string {
  if (min === null) return "";
  return max === null || max === min ? String(min) : `${min}-${max}`;
}

/** An empty box is absent, never `""` — the grammar refuses the other spelling. */
function textOrNull(value: string): string | null {
  const trimmed = value.trim();
  return trimmed === "" ? null : trimmed;
}

