/** The draft as `createLab` wants it. Empty fields are dropped, not sent as "". */
export function draftToCreateInput(draft: LabDraft) {
  const pricing = CELL_KEYS.flatMap(({ process, format, key }) => {
    if (draft.processes[process] !== true) return [];
    const cell = draft.pricing[key];
    if (!cell) return [];
    const priceThb = parsePrice(cell.price);
    const { min, max } = parseTurnaround(cell.turnaround);
    if (priceThb === null && min === null) return [];
    return [
      { process, format, priceThb, turnaroundMinD: min, turnaroundMaxD: max },
    ];
  });

  return {
    nameEn: draft.nameEn.trim(),
    nameTh: textOrNull(draft.nameTh),
    location: draft.location!,
    areaEn: textOrNull(draft.areaEn),
    areaTh: textOrNull(draft.areaTh),
    street: textOrNull(draft.street),
    landmarkNote: textOrNull(draft.landmarkNote),
    status: draft.status,
    statusNote: textOrNull(draft.statusNote),
    hours: draft.hours ?? undefined,
    processes: CHEM_PROCESSES.filter((p) => draft.processes[p] === true),
    scanners: Object.keys(draft.scanners).filter((m) => draft.scanners[m]),
    pricing,
    services: [
      ...Object.entries(draft.services)
        .filter(([, v]) => v.on)
        .map(([key, v]) => ({ key, note: textOrNull(v.note) })),
      ...draft.customServices
        .filter((s) => s.label.trim() !== "")
        .map((s) => ({
          customLabel: s.label.trim(),
          note: textOrNull(s.note ?? ""),
        })),
    ],
    supplies: [
      ...Object.keys(draft.supplies)
        .filter((k) => draft.supplies[k])
        .map((key) => ({ key })),
      ...draft.customSupplies
        .filter((s) => s.label.trim() !== "")
        .map((s) => ({ customLabel: s.label.trim() })),
    ],
    contacts: draft.contacts
      .filter((c) => c.value.trim() !== "")
      .map((c) => ({ id: c.id, channel: c.channel, value: c.value.trim() })),
    stock: draft.stock.map((s) => ({
      filmStockId: s.filmStockId,
      formats: s.formats,
    })),
  };
}

/** The create gate, so the button can be disabled rather than the save refused. */
export function createGate(draft: LabDraft): {
  ready: boolean;
  missing: string[];
} {
  const missing: string[] = [];
  if (draft.nameEn.trim() === "") missing.push("a name");
  if (draft.location === null) missing.push("a pin on the map");
  if (!CHEM_PROCESSES.some((p) => draft.processes[p] === true)) {
    missing.push("at least one process");
  }
  return { ready: missing.length === 0, missing };
}

